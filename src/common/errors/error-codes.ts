export interface FieldError {
  field: string;
  code: string;
  message: string;
}

/** Body of every error response (PRD ch.4: {code, message, fields[]}) */
export interface ErrorResponseBody {
  statusCode: number;
  code: string;
  message: string;
  fields?: FieldError[];
  requestId?: string;
}
